CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY, name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
  whatsapp TEXT, phone TEXT, role TEXT NOT NULL DEFAULT 'user', created_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS rates (
  id SERIAL PRIMARY KEY, name TEXT NOT NULL, unit TEXT NOT NULL CHECK (unit IN ('kg','piece')),
  rate NUMERIC(12,2) NOT NULL CHECK (rate >= 0));

CREATE TABLE IF NOT EXISTS requests (
  id SERIAL PRIMARY KEY, user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  material TEXT NOT NULL, unit TEXT NOT NULL, rate NUMERIC(12,2) NOT NULL, qty NUMERIC(12,2) NOT NULL CHECK (qty > 0),
  total NUMERIC(12,2) NOT NULL, address TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS listings (
  id SERIAL PRIMARY KEY, user_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL, category TEXT NOT NULL, cond TEXT NOT NULL, price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
  description TEXT NOT NULL, sold BOOLEAN NOT NULL DEFAULT false, created_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS messages (
  id SERIAL PRIMARY KEY, listing_id INT REFERENCES listings(id) ON DELETE SET NULL,
  request_id INT REFERENCES requests(id) ON DELETE SET NULL,
  from_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE, to_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now());

